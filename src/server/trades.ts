export type TradeFilters = {
  accountIds?: number[]
  symbols?: string[]
  from?: string
  to?: string
  direction?: 'long' | 'short'
  status?: 'open' | 'closed'
  limit?: number
  offset?: number
}

export function toTradeLike(trade: Trade): TradeLike {
  return {
    id: trade.id,
    accountId: trade.accountId,
    symbol: trade.symbol,
    direction: trade.direction,
    qty: trade.qty,
    entryAt: trade.entryAt,
    exitAt: trade.exitAt,
    tradingDay: trade.tradingDay,
    netPnl: trade.netPnl,
    grossPnl: trade.grossPnl,
    commission: trade.commission,
    fees: trade.fees,
    rMultiple: trade.rMultiple,
    riskBase: trade.riskBase,
    durationSeconds: trade.durationSeconds,
    setup: trade.setup,
    tags: trade.tags,
    mistakes: trade.mistakes,
    execScore: trade.execScore,
    status: trade.status,
  }
}

export async function listTrades(filters: TradeFilters = {}): Promise<Trade[]> {
  const conditions = []
  if (filters.accountIds?.length) conditions.push(inArray(trades.accountId, filters.accountIds))
  if (filters.symbols?.length) conditions.push(inArray(trades.symbol, filters.symbols))
  if (filters.from) conditions.push(gte(trades.tradingDay, filters.from))
  if (filters.to) conditions.push(lte(trades.tradingDay, filters.to))
  if (filters.direction) conditions.push(eq(trades.direction, filters.direction))
  if (filters.status) conditions.push(eq(trades.status, filters.status))

  return db
    .select()
    .from(trades)
    .where(conditions.length ? and(...conditions) : undefined)
    .orderBy(desc(trades.entryAt))
    .limit(filters.limit ?? 500)
    .offset(filters.offset ?? 0)
}

/**
 * Trades for analytics.
 *
 * Accounts flagged `excludeFromStats` are dropped here rather than at each call
 * site, so a demo account can never quietly inflate the headline numbers.
 */
export async function listTradesForStats(filters: TradeFilters = {}): Promise<TradeLike[]> {
  const included = await db
    .select({ id: accounts.id })
    .from(accounts)
    .where(eq(accounts.excludeFromStats, false))

  const ids = included.map((row) => row.id)
  if (ids.length === 0) return []

  const scoped = filters.accountIds?.length
    ? filters.accountIds.filter((id) => ids.includes(id))
    : ids
  if (scoped.length === 0) return []

  const rows = await listTrades({ ...filters, accountIds: scoped, limit: 20_000 })
  return rows.map(toTradeLike)
}

export async function listAccounts(): Promise<Account[]> {
  return db.select().from(accounts).orderBy(desc(accounts.status), asc(accounts.label))
}

/** Equity history per account, for the drawdown calculations. */
export async function equityHistory(): Promise<Record<number, { day: string; equity: number }[]>> {
  const rows = await db
    .select({
      accountId: dailyStats.accountId,
      day: dailyStats.tradingDay,
      equity: dailyStats.equity,
    })
    .from(dailyStats)
    .orderBy(asc(dailyStats.tradingDay))

  const out: Record<number, { day: string; equity: number }[]> = {}
  for (const row of rows) {
    ;(out[row.accountId] ??= []).push({ day: row.day, equity: row.equity })
  }
  return out
}

export async function countTrades(filters: TradeFilters = {}): Promise<number> {
  const conditions = []
  if (filters.accountIds?.length) conditions.push(inArray(trades.accountId, filters.accountIds))
  if (filters.from) conditions.push(gte(trades.tradingDay, filters.from))
  if (filters.to) conditions.push(lte(trades.tradingDay, filters.to))

  const [row] = await db
    .select({ count: sql<number>`count(*)::int` })
    .from(trades)
    .where(conditions.length ? and(...conditions) : undefined)
  return row?.count ?? 0
}
